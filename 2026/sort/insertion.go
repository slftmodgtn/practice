package sort

import (
	"cmp"
	"slices"
)

// InsertionSortClassic реализует классическую сортировку вставками с пошаговым сдвигом элементов.
// Сложность по времени: O(N^2) в худшем и среднем случае, O(N) в лучшем (для уже отсортированного массива).
func InsertionSortClassic[T cmp.Ordered](arr []T) {
	for i := 1; i < len(arr); i++ {
		// Сохраняем текущий элемент для вставки, так как при сдвиге он будет перезаписан
		key := arr[i]
		j := i - 1
		// Ищем индекс для вставки в отсортированной части, одновременно сдвигая элементы вправо по одному
		for j >= 0 && arr[j] > key {
			arr[j+1] = arr[j]
			j--
		}
		// Вставляем сохраненный элемент на найденную позицию
		arr[j+1] = key
	}
}

// InsertionSortShift реализует сортировку вставками с использованием copy для сдвига поддиапазона.
// Сложность по времени: O(N^2) в худшем и среднем случае, O(N) в лучшем.
func InsertionSortShift[T cmp.Ordered](arr []T) {
	for i := 1; i < len(arr); i++ {
		// Сохраняем текущий элемент, так как при сдвиге он будет перезаписан
		key := arr[i]
		j := i - 1
		// Ищем индекс для вставки в отсортированной части
		for j >= 0 && arr[j] > key {
			j--
		}
		// Вычисляем точную позицию вставки (j + 1 корректно работает и при j = -1)
		pos := j + 1
		// Сдвигаем элементы вправо за один вызов copy, освобождая место для вставки
		copy(arr[pos+1:i+1], arr[pos:i])
		// Вставляем сохраненный элемент на найденную позицию
		arr[pos] = key
	}
}

// InsertionSortRange реализует сортировку вставками с использованием конструкции range.
// Сложность по времени: O(N^2) в худшем и среднем случае, O(N) в лучшем.
func InsertionSortRange[T cmp.Ordered](arr []T) {
	for i, val := range arr {
		j := i - 1
		for j >= 0 && arr[j] > val {
			arr[j+1] = arr[j]
			j--
		}
		arr[j+1] = val
	}
}

// InsertionSortStdBinary сортирует срез с помощью бинарной сортировки вставками,
// используя стандартную функцию slices.BinarySearch для поиска позиции вставки.
// Это снижает количество сравнений элементов до O(N log N), хотя сдвиги остаются O(N^2).
func InsertionSortStdBinary[T cmp.Ordered](arr []T) {
	for i := 1; i < len(arr); i++ {
		// Сохраняем текущий элемент для вставки
		val := arr[i]

		// Ищем индекс для вставки в уже отсортированной части с помощью бинарного поиска
		// `slices.BinarySearch` возвращает индекс в диапазоне от 0 до len(arr):
		//   - Если число меньше всех элементов в отсортированной части, возвращает 0.
		//   - Если число больше всех элементов, возвращает len(arr).
		//   - Если число посередине, возвращает индекс первого элемента, большего или равного числу.
		j, _ := slices.BinarySearch(arr[:i], val)

		// Если элемент нужно вставить не на его текущую позицию
		if j < i {
			// Сдвигаем элементы вправо, освобождая место для вставки
			copy(arr[j+1:i+1], arr[j:i])
			// Вставляем сохраненный элемент на найденную позицию
			arr[j] = val
		}
	}
}

// InsertionSortCustomBinary сортирует срез с помощью бинарной сортировки вставками,
// используя собственную реализацию алгоритма бинарного поиска позиции вставки.
// Снижает количество сравнений до O(N log N).
func InsertionSortCustomBinary[T cmp.Ordered](arr []T) {
	for i := 1; i < len(arr); i++ {
		// Сохраняем текущий элемент для вставки, так как при сдвиге он будет перезаписан
		val := arr[i]

		// Ищем индекс для вставки в уже отсортированной части (от 0 до i-1) с помощью бинарного поиска
		low, high := 0, i
		for low < high {
			// Вычисляем средний индекс проверяемого диапазона
			mid := low + (high-low)/2
			// Если элемент в середине больше вставляемого, искомая позиция левее или равна mid
			if arr[mid] > val {
				high = mid
			} else {
				// Иначе искомая позиция правее mid
				low = mid + 1
			}
		}

		// Если элемент нужно вставить не на его текущую позицию
		if low < i {
			// Сдвигаем элементы вправо, освобождая место для вставки
			copy(arr[low+1:i+1], arr[low:i])
			// Вставляем сохраненный элемент на найденную позицию
			arr[low] = val
		}
	}
}
